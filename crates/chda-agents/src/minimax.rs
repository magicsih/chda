impl AgentAdapter for MiniMaxAdapter {
    fn id(&self) -> AgentId {
        AgentId::MiniMax
    }
    fn display_name(&self) -> &str {
        "MiniMax Code"
    }
    fn short_label(&self) -> String {
        "MM".into()
    }
    fn is_installed(&self, path: &OsStr) -> bool {
        which("mcode", path).is_some()
    }
    fn executable(&self, _: &Path, path: &OsStr) -> Option<PathBuf> {
        which("mcode", path)
    }
    fn launch_command(&self, cwd: &Path, _: Option<&SessionId>, _: &Path) -> Command {
        let mut cmd = Command::new("mcode");
        cmd.current_dir(cwd);
        cmd
    }
    fn session_roots(&self) -> Vec<PathBuf> {
        Vec::new()
    }
    fn parse_session(&self, _: &Path) -> Option<AgentSession> {
        None
    }
    fn install_hooks(&self, _: &Path, _: &Path) -> io::Result<HookInstallReport> {
        // Startup must not install anything into the user's provider directory.
        Ok(HookInstallReport {
            file: None,
            note: None,
        })
    }
}

fn package() -> BTreeMap<String, Vec<u8>> {
    let manifest = json!({
        "schemaVersion": 1, "name": "chda-status", "version": "1.0.0",
        "description": "Reports managed pane status to chda", "author": "chda",
        "icon": "icon.png", "category": "Code", "exampleQueries": [],
        "apps": [], "mcpServers": [], "skills": [], "hooks": ["hooks.json"]
    });
    let mut hooks = serde_json::Map::new();
    for event in [
        "SessionStart",
        "UserPromptSubmit",
        "PermissionRequest",
        "PostToolUse",
        "Stop",
        "SessionEnd",
    ] {
        hooks.insert(
            event.into(),
            json!([{ "hooks": [{
            "type": "command", "command": "node \"${PLUGIN_ROOT}/report.cjs\"", "timeout": 10
        }] }]),
        );
    }
    BTreeMap::from([
        (
            ".minimax-plugin/plugin.json".into(),
            serde_json::to_vec_pretty(&manifest).unwrap(),
        ),
        (
            "hooks.json".into(),
            serde_json::to_vec_pretty(&json!({"hooks": hooks})).unwrap(),
        ),
        ("report.cjs".into(), HELPER.to_vec()),
        ("icon.png".into(), ICON.to_vec()),
    ])
}

/// Verify ownership before replacing any generated byte. The saved snapshot
/// also makes an interrupted replacement recoverable without touching user data.
pub fn install_plugin(provider_dir: &Path, data_dir: &Path) -> io::Result<PathBuf> {
    let root = provider_dir.join("plugins/chda-status");
    let files = package();
    if fs::symlink_metadata(&root).is_ok() {
        if !fs::symlink_metadata(&root)?.is_dir() {
            return Err(collision());
        }
        if !fs::symlink_metadata(root.join(".minimax-plugin")).is_ok_and(|m| m.is_dir()) {
            return Err(collision());
        }
        let snapshot: BTreeMap<String, Vec<u8>> = fs::read(root.join(OWNER))
            .ok()
            .and_then(|b| serde_json::from_slice(&b).ok())
            .ok_or_else(collision)?;
        if snapshot.keys().ne(files.keys()) {
            return Err(collision());
        }
        for (name, bytes) in &snapshot {
            let path = root.join(name);
            if !fs::symlink_metadata(&path).is_ok_and(|m| m.is_file()) || fs::read(&path)? != *bytes
            {
                return Err(collision());
            }
        }
        if snapshot == files {
            return Ok(root);
        }
        let backup = data_dir.join("hooks/minimax/plugin-backups").join(format!(
            "{}-{}.json",
            crate::hook::now_ms(),
            std::process::id()
        ));
        ipc::write_private_atomic(&backup, &serde_json::to_vec(&snapshot)?)?;
    }
    fs::create_dir_all(&root)?;
    // Publish the manifest last, so an incomplete first installation is not a plugin.
    for (name, bytes) in files
        .iter()
        .filter(|(name, _)| !name.ends_with("plugin.json"))
    {
        ipc::write_private_atomic(&root.join(name), bytes)?;
    }
    ipc::write_private_atomic(
        &root.join(".minimax-plugin/plugin.json"),
        &files[".minimax-plugin/plugin.json"],
    )?;
    ipc::write_private_atomic(&root.join(OWNER), &serde_json::to_vec(&files)?)?;
    Ok(root)
}

fn collision() -> io::Error {
    io::Error::other(
        "MiniMax chda-status plugin exists with unrecognized or modified files; it was preserved",
    )
}

pub fn context_dir(data_dir: &Path, pane: u64) -> PathBuf {
    data_dir
        .join("hooks/minimax")
        .join(format!("chda-minimax-pane-{pane}"))
}

/// Only named context files owned by this pane; keep them during app adoption.
pub fn remove_context(data_dir: &Path, pane: u64) {
    let dir = context_dir(data_dir, pane);
    if !fs::symlink_metadata(&dir).is_ok_and(|m| m.is_dir()) {
        return;
    }
    for name in ["context.json", "state.json"] {
        let _ = fs::remove_file(dir.join(name));
    }
    let _ = fs::remove_dir(dir);
}

/// Prepare only the selected managed launch. Native hooks retain PATH but drop
/// CHDA_* and XDG_* variables, so the plugin recovers routing from this directory.
pub struct LaunchPreparation<'a> {
    pub home: &'a Path,
    pub cwd: &'a Path,
    pub data_dir: &'a Path,
    pub hook_bin: &'a Path,
    pub pane: u64,
    pub executable: &'a Path,
    pub search_path: &'a OsStr,
    pub environment: &'a [(String, String)],
}

pub fn prepare_launch(launch: &LaunchPreparation<'_>) -> io::Result<std::ffi::OsString> {
    let LaunchPreparation {
        home,
        cwd,
        data_dir,
        hook_bin,
        pane,
        executable,
        search_path,
        environment,
    } = launch;
    let get = |name: &str| {
        environment
            .iter()
            .rev()
            .find(|(k, _)| k == name)
            .map(|(_, v)| v.clone())
            .or_else(|| std::env::var(name).ok())
            .filter(|v| !v.trim().is_empty())
    };
    if get("__MAVIS_RUNTIME_PROFILE").is_some() {
        return Err(io::Error::other(
            "For a MiniMax profile, supply its explicit MINIMAX_DATA_DIR before launching",
        ));
    }
    let provider_dir = get("MINIMAX_DATA_DIR")
        .or_else(|| get("MAVIS_DATA_DIR"))
        .map(|p| cwd.join(p.trim()))
        .unwrap_or_else(|| home.join(".minimax"));
    if which("node", search_path).is_none() {
        return Err(io::Error::other(
            "MiniMax status needs Node.js on the pane's PATH",
        ));
    }
    let mut probe = Command::new(executable);
    probe
        .arg("--version")
        .current_dir(cwd)
        .envs(environment.iter().map(|(k, v)| (k, v)))
        .env("PATH", search_path);
    let version = ipc::capture_command(&mut probe, None, std::time::Duration::from_secs(3), 128)?;
    let version = String::from_utf8_lossy(&version);
    let parts: Vec<u32> = version
        .trim()
        .split('.')
        .filter_map(|p| p.parse().ok())
        .collect();
    if parts.as_slice() < [0, 6, 12].as_slice() || parts.len() != 3 {
        return Err(io::Error::other(
            "MiniMax status requires mcode 0.6.12 or later",
        ));
    }
    install_plugin(&provider_dir, data_dir)?;
    let context = context_dir(data_dir, *pane);
    if fs::symlink_metadata(&context).is_ok_and(|m| !m.is_dir()) {
        return Err(collision());
    }
    fs::create_dir_all(&context)?;
    let value = json!({"version": 1, "pane": pane, "hook_bin": hook_bin, "data_dir": data_dir});
    ipc::write_private_atomic(&context.join("context.json"), &serde_json::to_vec(&value)?)?;
    let paths = std::iter::once(context).chain(std::env::split_paths(search_path));
    std::env::join_paths(paths).map_err(io::Error::other)
}
